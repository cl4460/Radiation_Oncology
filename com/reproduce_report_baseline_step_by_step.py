def mrmr_select(
    X: pd.DataFrame,
    time: np.ndarray,
    event: np.ndarray,
    k: int,
    seed: int = 0,
    relevance: str = "event+time",
    redundancy: str = "corr",
) -> List[str]:
    """
    A practical mRMR approximation for survival:
      relevance:
        - "event": MI(feature, event)
        - "time":  MI(feature, log1p(time))
        - "event+time": sum of both
      redundancy:
        - "corr": mean absolute Pearson corr with selected features

    NOTE: This may not match a specific external mRMR library exactly,
    but it is stable and easy to audit.
    """
    rng = np.random.default_rng(seed)
    cols = list(X.columns)
    Xv = X.to_numpy(dtype=float)

    # relevance
    rel = np.zeros(Xv.shape[1], dtype=float)
    if relevance in ("event", "event+time"):
        rel += mutual_info_classif(Xv, event.astype(int), random_state=seed, discrete_features=False)
    if relevance in ("time", "event+time"):
        rel += mutual_info_regression(Xv, np.log1p(time.astype(float)), random_state=seed)

    # start: best relevance
    selected = []
    remaining = list(range(Xv.shape[1]))
    first = int(np.nanargmax(rel))
    selected.append(first)
    remaining.remove(first)

    # precompute corr matrix progressively (cheap enough for k<=100)
    for _ in range(1, k):
        best_idx = None
        best_score = -np.inf
        for j in remaining:
            if redundancy == "corr" and len(selected) > 0:
                # mean abs corr with selected
                r = []
                xj = Xv[:, j]
                for s in selected:
                    xs = Xv[:, s]
                    # safe corr
                    if np.std(xj) < 1e-12 or np.std(xs) < 1e-12:
                        r.append(0.0)
                    else:
                        r.append(abs(np.corrcoef(xj, xs)[0, 1]))
                red = float(np.mean(r)) if r else 0.0
            else:
                red = 0.0
            score = rel[j] - red
            # tie-breaker by tiny noise for determinism
            score += 1e-12 * rng.normal()
            if score > best_score:
                best_score = score
                best_idx = j
        selected.append(best_idx)
        remaining.remove(best_idx)

    return [cols[i] for i in selected]


