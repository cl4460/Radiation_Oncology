def harrell_c_index(event: np.ndarray, time: np.ndarray, risk: np.ndarray) -> float:
    """
    Harrell's C-index for right-censored survival.

    event: boolean (True if event observed)
    time: survival/censor time
    risk: higher means higher hazard (shorter survival)

    Comparable pairs: (i,j) where time_i < time_j and event_i == True.
    Concordant if risk_i > risk_j, ties contribute 0.5.
    """
    event = event.astype(bool)
    time = time.astype(float)
    risk = risk.astype(float)

    n = len(time)
    concordant = 0.0
    discordant = 0.0
    tied_risk = 0.0
    comparable = 0.0

    for i in range(n):
        if not event[i]:
            continue
        ti = time[i]
        ri = risk[i]
        # only compare to those with longer time
        for j in range(n):
            if ti < time[j]:
                comparable += 1.0
                rj = risk[j]
                if ri > rj:
                    concordant += 1.0
                elif ri < rj:
                    discordant += 1.0
                else:
                    tied_risk += 1.0

    if comparable == 0:
        return float("nan")
    return float((concordant + 0.5 * tied_risk) / comparable)


def bootstrap_cindex(
    df: pd.DataFrame,
    risk_col: str,
    time_col: str,
    event_col: str,
    n_boot: int = 200,
    seed: int = 0,
) -> Dict[str, float]:
    """
    Bootstrap resampling on rows; return mean/std and two CIs:
      - percentile CI
      - normal-approx CI (mean ± 1.96*std)  (often what "report" tables implicitly use)
    """
    rng = np.random.default_rng(seed)
    event = df[event_col].astype(bool).to_numpy()
    time = df[time_col].astype(float).to_numpy()
    risk = df[risk_col].astype(float).to_numpy()
    n = len(df)

    vals = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        vals.append(harrell_c_index(event[idx], time[idx], risk[idx]))
    vals = np.asarray(vals, dtype=float)

    mean = float(np.nanmean(vals))
    std = float(np.nanstd(vals, ddof=1))
    p025, p975 = np.nanpercentile(vals, [2.5, 97.5])

    z = 1.96
    ci_norm_lo = mean - z * std
    ci_norm_hi = mean + z * std

    return {
        "boot_mean": mean,
        "boot_std": std,
        "ci_pct_2.5": float(p025),
        "ci_pct_97.5": float(p975),
        "ci_norm_2.5": float(ci_norm_lo),
        "ci_norm_97.5": float(ci_norm_hi),
    }


