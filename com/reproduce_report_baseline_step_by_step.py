def load_radiomics_csv(path: str, id_col: str = "PatientID") -> pd.DataFrame:
    df = pd.read_csv(path)
    if id_col not in df.columns:
        raise ValueError(f"[radiomics] id_col='{id_col}' not found. available: {df.columns.tolist()[:20]} ...")
    df[id_col] = df[id_col].astype(str)
    df = df.set_index(id_col)

    # drop non-numeric columns (if any)
    keep_cols = []
    for c in df.columns:
        if pd.api.types.is_numeric_dtype(df[c]):
            keep_cols.append(c)
        else:
            # try coerce
            coerced = pd.to_numeric(df[c], errors="coerce")
            if coerced.notna().sum() > 0:
                df[c] = coerced
                keep_cols.append(c)
    df = df[keep_cols]
    return df


def preprocess_radiomics(
    rad: pd.DataFrame,
    train_ids: List[str],
    scale: str = "minmax",
    impute: str = "mean",
) -> Tuple[pd.DataFrame, Dict[str, object]]:
    fitted: Dict[str, object] = {}

    # impute
    imp = SimpleImputer(strategy=impute)
    imp.fit(rad.loc[train_ids])
    X = pd.DataFrame(imp.transform(rad), columns=rad.columns, index=rad.index)
    fitted["imputer"] = imp

    # scale
    if scale == "minmax":
        scaler = MinMaxScaler()
        scaler.fit(X.loc[train_ids])
        X = pd.DataFrame(scaler.transform(X), columns=X.columns, index=X.index)
        fitted["scaler"] = scaler
    elif scale == "none":
        pass
    else:
        raise ValueError(f"Unsupported radiomics scale: {scale}")

    return X, fitted


