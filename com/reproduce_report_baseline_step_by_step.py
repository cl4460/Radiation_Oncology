def fit_predict_cph(
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    time_train: np.ndarray,
    event_train: np.ndarray,
    time_test: np.ndarray,
    event_test: np.ndarray,
    alpha: float = 0.0,
    ties: str = "efron",
    n_iter: Optional[int] = None,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    CoxPH with ties=efron if lifelines is installed; else fallback to sksurv CoxPHSurvivalAnalysis (ties may differ).
    Returns (risk_train, risk_test).
    """
    # Prefer lifelines because the artifact best_params includes "ties: efron".
    try:
        from lifelines import CoxPHFitter
    except Exception:
        CoxPHFitter = None

    if CoxPHFitter is not None:
        df_tr = X_train.copy()
        df_tr["time"] = time_train
        df_tr["event"] = event_train.astype(int)
        cph = CoxPHFitter(penalizer=float(alpha))
        fit_opts = {}
        if n_iter is not None:
            fit_opts['max_steps'] = int(n_iter)
        cph.fit(df_tr, duration_col='time', event_col='event', show_progress=False, fit_options=(fit_opts or None))

        risk_tr = cph.predict_partial_hazard(X_train).to_numpy().reshape(-1)
        risk_te = cph.predict_partial_hazard(X_test).to_numpy().reshape(-1)
        return risk_tr, risk_te

    # fallback: sksurv
    try:
        from sksurv.linear_model import CoxPHSurvivalAnalysis
        from sksurv.util import Surv
    except Exception as e:
        raise RuntimeError(
            "Neither lifelines nor scikit-survival is available. "
            "Install one of them. For best match with report, install lifelines."
        ) from e

    y_train = Surv.from_arrays(event_train.astype(bool), time_train.astype(float))
    model = CoxPHSurvivalAnalysis(alpha=float(alpha))
    model.fit(X_train.to_numpy(), y_train)
    risk_tr = model.predict(X_train.to_numpy()).reshape(-1)
    risk_te = model.predict(X_test.to_numpy()).reshape(-1)
    return risk_tr, risk_te


def fit_predict_coxnet_cv(
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    time_train: np.ndarray,
    event_train: np.ndarray,
    seed: int,
    l1_ratio: float = 0.001,
    n_alphas: int = 20,
    n_folds: int = 5,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, float]]:
    """
    CoxNet (elastic-net) with CV selection of alpha by mean Harrell C-index across folds.

    Returns:
      risk_train (using best alpha, refit on full train)
      risk_test
      info dict: best_alpha, best_cv_cindex
    """
    try:
        from sksurv.linear_model import CoxnetSurvivalAnalysis
        from sksurv.util import Surv
    except Exception as e:
        raise RuntimeError("scikit-survival is required for CoxNet reproduction.") from e

    Xtr = X_train.to_numpy(dtype=float)
    Xte = X_test.to_numpy(dtype=float)
    y = Surv.from_arrays(event_train.astype(bool), time_train.astype(float))

    # Fit once to get alpha path
    base = CoxnetSurvivalAnalysis(
    l1_ratio=float(l1_ratio),
    n_alphas=int(n_alphas),
    alpha_min_ratio=1e-4,)
    base.fit(Xtr, y)

    # The library stores alphas_ after fit
    alphas = getattr(base, "alphas_", None)
    if alphas is None:
        # fall back to user-provided alphas if needed
        raise RuntimeError("CoxnetSurvivalAnalysis did not expose alphas_. Please check scikit-survival version.")

    kf = KFold(n_splits=int(n_folds), shuffle=True, random_state=int(seed))
    cv_scores = np.zeros_like(alphas, dtype=float)
    cv_counts = np.zeros_like(alphas, dtype=float)

    for tr_idx, va_idx in kf.split(Xtr):
        X_tr, X_va = Xtr[tr_idx], Xtr[va_idx]
        y_tr = Surv.from_arrays(event_train[tr_idx].astype(bool), time_train[tr_idx].astype(float))

        m = CoxnetSurvivalAnalysis(l1_ratio=float(l1_ratio), alphas=alphas)
        m.fit(X_tr, y_tr)

        # predict may return (n_samples, n_alphas) or (n_samples,) depending on version
        pred = m.predict(X_va)
        if pred.ndim == 1:
            pred = pred.reshape(-1, 1)

        # compute c-index for each alpha
        ev_va = event_train[va_idx].astype(bool)
        tm_va = time_train[va_idx].astype(float)
        for j in range(pred.shape[1]):
            c = harrell_c_index(ev_va, tm_va, pred[:, j])
            if not np.isnan(c):
                cv_scores[j] += c
                cv_counts[j] += 1

    mean_cv = np.divide(cv_scores, np.maximum(cv_counts, 1.0))
    best_j = int(np.nanargmax(mean_cv))
    best_alpha = float(alphas[best_j])
    best_cv = float(mean_cv[best_j])

    # Refit final model on full train using only best alpha
    final = CoxnetSurvivalAnalysis(l1_ratio=float(l1_ratio), alphas=[best_alpha])
    final.fit(Xtr, ytr)
    if np.all(final.coef_ == 0):
        # fallback to smallest alpha
        best_alpha = float(np.min(alphas))
        final = CoxnetSurvivalAnalysis(l1_ratio=float(l1_ratio), alphas=[best_alpha])
        final.fit(Xtr, ytr)
    risk_tr = final.predict(Xtr).reshape(-1)
    risk_te = final.predict(Xte).reshape(-1)

    return risk_tr, risk_te, {"best_alpha": best_alpha, "best_cv_cindex": best_cv}


def fit_predict_gbsa(
    X_train: pd.DataFrame,
    X_test: pd.DataFrame,
    time_train: np.ndarray,
    event_train: np.ndarray,
    params: Dict[str, object],
) -> Tuple[np.ndarray, np.ndarray]:
    """
    GradientBoostingSurvivalAnalysis (scikit-survival).
    Params should include keys like in best_params_*.yaml from artifacts.
    """
    try:
        from sksurv.ensemble import GradientBoostingSurvivalAnalysis
        from sksurv.util import Surv
    except Exception as e:
        raise RuntimeError("scikit-survival is required for GBSA reproduction.") from e

    # Filter only valid GBSA params (robust to extras)
    valid = {
        "loss", "learning_rate", "n_estimators", "subsample",
        "criterion", "dropout_rate", "max_depth", "max_leaf_nodes",
        "max_features", "min_samples_split", "min_samples_leaf",
        "min_weight_fraction_leaf", "min_impurity_decrease",
        "random_state"
    }
    gb_params = {k: params[k] for k in params.keys() if k in valid}

    # Ensure correct types
    if "random_state" not in gb_params:
        gb_params["random_state"] = 0

    model = GradientBoostingSurvivalAnalysis(**gb_params)
    y_train = Surv.from_arrays(event_train.astype(bool), time_train.astype(float))

    model.fit(X_train.to_numpy(dtype=float), y_train)
    risk_tr = model.predict(X_train.to_numpy(dtype=float)).reshape(-1)
    risk_te = model.predict(X_test.to_numpy(dtype=float)).reshape(-1)
    return risk_tr, risk_te


