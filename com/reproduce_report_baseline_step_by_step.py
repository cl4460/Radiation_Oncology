def load_clinical_csv(path: str, id_col: str = "PatientID") -> pd.DataFrame:
    df = pd.read_csv(path)
    if id_col not in df.columns:
        raise ValueError(f"[clinical] id_col='{id_col}' not found. available: {df.columns.tolist()[:20]} ...")
    df[id_col] = df[id_col].astype(str)
    df = df.set_index(id_col)
    return df


def build_xy_from_raw(
    clinical_csv: str,
    radiomics_csv: str,
    clinical_id_col: str,
    radiomics_id_col: str,
    time_col: str,
    event_col: str,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]:
    clin = load_clinical_csv(clinical_csv, id_col=clinical_id_col)
    rad = load_radiomics_csv(radiomics_csv, id_col=radiomics_id_col)

    # intersection on patient IDs
    common = clin.index.intersection(rad.index)
    clin = clin.loc[common].copy()
    rad = rad.loc[common].copy()

    # labels from clinical
    time = pd.to_numeric(clin[time_col], errors="coerce")
    event = pd.to_numeric(clin[event_col], errors="coerce").fillna(0).astype(int)

    # Remove rows with missing time
    keep = time.notna()
    clin = clin.loc[keep]
    rad = rad.loc[keep]
    time = time.loc[keep]
    event = event.loc[keep]

    return clin, rad, time, event


def ensure_ids_exist(ids: List[str], index: pd.Index, name: str) -> List[str]:
    idx_set = set(index.astype(str).tolist())
    miss = [i for i in ids if i not in idx_set]
    if miss:
        print(f"[WARN] {name}: {len(miss)} ids not found in your dataset. First few: {miss[:10]}", file=sys.stderr)
    return [i for i in ids if i in idx_set]



def load_split_json(path: str) -> Tuple[List[str], List[str]]:
    """
    Load a custom split json. Supported formats:
      - {'train_ids': [...], 'val_ids': [...], 'test_ids': [...]}
      - {'train': [...], 'val': [...], 'test': [...]}
    Training will use (train_ids + val_ids) if val exists.
    """
    with open(path, 'r', encoding='utf-8') as f:
        d = json.load(f)
    train_ids = d.get('train_ids', d.get('train', []))
    val_ids = d.get('val_ids', d.get('val', []))
    test_ids = d.get('test_ids', d.get('test', []))
    train_ids = [str(x) for x in train_ids] if train_ids is not None else []
    val_ids = [str(x) for x in val_ids] if val_ids is not None else []
    test_ids = [str(x) for x in test_ids] if test_ids is not None else []
    train_all = train_ids + val_ids
    if not train_all:
        raise ValueError(f"split_json has empty train (and val) ids: {path}")
    if not test_ids:
        raise ValueError(f"split_json has empty test ids: {path}")
    return train_all, test_ids

def run_one(
    task: str,
    model: str,
    clin_raw: pd.DataFrame,
    rad_raw: pd.DataFrame,
    time: pd.Series,
    event: pd.Series,
    train_ids: List[str],
    test_ids: List[str],
    selected_features: Optional[List[str]],
    best_params: Dict[str, object],
    seed: int,
    mode: str,
    mrmr_ratio: float,
    mrmr_k: Optional[int],
    bootstrap: int,
    out_dir: str,
    clinical_flags: Dict[str, int],
    age_impute: str,
) -> Dict[str, object]:
    """
    mode:
      - exact: use selected_features from artifacts
      - scratch: compute mRMR on train (radiomics only) then optionally fuse
    """
    os.makedirs(out_dir, exist_ok=True)

    # ensure ids exist after intersection
    train_ids = ensure_ids_exist(train_ids, clin_raw.index, "train_ids")
    test_ids = ensure_ids_exist(test_ids, clin_raw.index, "test_ids")

    y_time = time.astype(float)
    y_event = event.astype(int)

    # build clinical matrix (always build "full" to allow selecting artifact one-hot columns)
    X_clin, _ = build_clinical_matrix(
        clin_raw,
        train_ids=train_ids,
        age_impute=age_impute,
        use_age=clinical_flags["use_age"],
        use_gender=clinical_flags["use_gender"],
        use_histology=clinical_flags["use_histology"],
        use_t_stage=clinical_flags["use_t_stage"],
        use_n_stage=clinical_flags["use_n_stage"],
        use_m_stage=clinical_flags["use_m_stage"],
        use_stage=clinical_flags["use_stage"],
        scale_numeric=True,
    )

    # radiomics preprocess
    X_rad, _ = preprocess_radiomics(rad_raw, train_ids=train_ids, scale="minmax", impute="mean")

    if task.lower() == "radiomics":
        X_all = X_rad
    elif task.lower() == "clinic":
        X_all = X_clin
    elif task.lower() in ("clinic+radiomics", "fusion"):
        X_all = pd.concat([X_rad, X_clin], axis=1)
    else:
        raise ValueError(f"Unknown task: {task}")

    # feature selection
    if mode == "exact":
        if not selected_features:
            raise ValueError("EXACT mode requires selected_features from recipe/artifacts.")
        # select subset
        missing = [f for f in selected_features if f not in X_all.columns]
        if missing:
            raise ValueError(
                f"Some selected features are missing from your constructed matrix (n={len(missing)}). "
                f"First few: {missing[:10]}\n"
                f"Tip: this usually means your clinical one-hot coding does NOT match the report."
            )
        X_use = X_all[selected_features].copy()
        selected = selected_features
    elif mode == "scratch":
        # mRMR only on radiomics (report style); then build task matrix
        # Decide K
        if mrmr_k is not None:
            k = int(mrmr_k)
        else:
            k = int(np.ceil(X_rad.shape[1] * float(mrmr_ratio)))
        k = max(1, min(k, X_rad.shape[1]))
        sel = mrmr_select(
            X=X_rad.loc[train_ids],
            time=y_time.loc[train_ids].to_numpy(),
            event=y_event.loc[train_ids].to_numpy(),
            k=k,
            seed=seed,
            relevance="event+time",
            redundancy="corr",
        )
        if task.lower() == "radiomics":
            X_use = X_rad[sel].copy()
        elif task.lower() == "clinic":
            X_use = X_clin.copy()
        else:
            X_use = pd.concat([X_rad[sel], X_clin], axis=1).copy()
        selected = list(X_use.columns)
    else:
        raise ValueError(f"Unknown mode: {mode}")

    # split matrices
    X_train = X_use.loc[train_ids]
    X_test = X_use.loc[test_ids]
    t_train = y_time.loc[train_ids].to_numpy()
    e_train = y_event.loc[train_ids].to_numpy().astype(bool)
    t_test = y_time.loc[test_ids].to_numpy()
    e_test = y_event.loc[test_ids].to_numpy().astype(bool)

    # fit model
    if model == "cph":
        alpha = float(best_params.get("alpha", 0.0))
        ties = str(best_params.get("ties", "efron"))
        n_iter = best_params.get('n_iter', None)
        risk_tr, risk_te = fit_predict_cph(X_train, X_test, t_train, e_train, t_test, e_test, alpha=alpha, ties=ties, n_iter=n_iter)
        extra = {'alpha': alpha, 'ties': ties, 'n_iter': n_iter}
    elif model == "coxnet":
        l1_ratio = float(best_params.get("l1_ratio", 0.001))
        n_alphas = int(best_params.get("n_alphas", 20))
        risk_tr, risk_te, info = fit_predict_coxnet_cv(
            X_train, X_test, t_train, e_train, seed=seed, l1_ratio=l1_ratio, n_alphas=n_alphas, n_folds=5
        )
        extra = {"l1_ratio": l1_ratio, "n_alphas": n_alphas, **info}
    elif model == "gbsa":
        risk_tr, risk_te = fit_predict_gbsa(X_train, X_test, t_train, e_train, best_params)
        extra = dict(best_params)
    else:
        raise ValueError(f"Unknown model: {model}")

    # scores
    train_ci = harrell_c_index(e_train, t_train, risk_tr)
    test_ci = harrell_c_index(e_test, t_test, risk_te)

    df_test = pd.DataFrame({
        "pid": test_ids,
        "time": t_test,
        "event": e_test.astype(int),
        "pred_risk": risk_te,
    })
    boot = bootstrap_cindex(df_test, risk_col="pred_risk", time_col="time", event_col="event", n_boot=bootstrap, seed=seed)

    out = {
        "task": task,
        "model": model,
        "mode": mode,
        "n_train": int(len(train_ids)),
        "n_test": int(len(test_ids)),
        "n_features": int(X_use.shape[1]),
        "train_cindex": float(train_ci),
        "test_cindex": float(test_ci),
        **boot,
        "selected_features": selected,
        "model_params": extra,
    }

    # save artifacts
    out_path = os.path.join(out_dir, f"result_{task.replace('+','_')}_{model}_{mode}.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    pred_path = os.path.join(out_dir, f"test_preds_{task.replace('+','_')}_{model}_{mode}.csv")
    df_test.to_csv(pred_path, index=False)

    return out


def main():
    parser = argparse.ArgumentParser(description="Reproduce experiment-report baselines step-by-step.")
    sub = parser.add_subparsers(dest="cmd", required=True)

    # extract
    p_ext = sub.add_parser("extract", help="Extract report recipe (splits/features/params) from 实验结果.zip")
    p_ext.add_argument("--report_zip", required=True, help="Path to 实验结果.zip")
    p_ext.add_argument("--out_dir", required=True, help="Where to write report_recipe.json and unpacked files")

    # run
    p_run = sub.add_parser("run", help="Run reproduction using a recipe (exact) or from scratch (scratch)")
    p_run.add_argument("--clinical_csv", required=True)
    p_run.add_argument("--radiomics_csv", required=True)
    p_run.add_argument("--recipe_json", required=False, default=None, help="Path to report_recipe.json (from extract)")
    p_run.add_argument("--split_json", required=False, default=None, help="Optional custom split json (train_ids/val_ids/test_ids). If provided, overrides recipe split.")
    p_run.add_argument("--task", required=True, choices=["Radiomics", "Clinic", "Clinic+Radiomics", "Fusion", "fusion"])
    p_run.add_argument("--model", required=True, choices=["cph", "coxnet", "gbsa", "all"])
    p_run.add_argument("--mode", required=True, choices=["exact", "scratch"])
    p_run.add_argument("--seed", type=int, default=9)
    p_run.add_argument("--out_dir", required=True)

    # columns
    p_run.add_argument("--clinical_id_col", default="PatientID")
    p_run.add_argument("--radiomics_id_col", default="PatientID")
    p_run.add_argument("--time_col", default="Survival.time")
    p_run.add_argument("--event_col", default="deadstatus.event")

    # scratch feature selection
    p_run.add_argument("--mrmr_ratio", type=float, default=0.01)
    p_run.add_argument("--mrmr_k", type=int, default=None)

    # clinical flags (only meaningful in scratch mode; in exact mode keep them ON to match recipe)
    p_run.add_argument("--use_age", type=int, default=1)
    p_run.add_argument("--use_gender", type=int, default=1)
    p_run.add_argument("--use_histology", type=int, default=1)
    p_run.add_argument("--use_t_stage", type=int, default=1)
    p_run.add_argument("--use_n_stage", type=int, default=1)
    p_run.add_argument("--use_m_stage", type=int, default=1)
    p_run.add_argument("--use_stage", type=int, default=1)
    p_run.add_argument("--age_impute", default="mean", choices=["mean", "median"])

    # eval
    p_run.add_argument("--bootstrap", type=int, default=200)

    args = parser.parse_args()

    if args.cmd == "extract":
        recipe_json = extract_recipe(args.report_zip, args.out_dir)
        print(f"[OK] recipe_json saved to: {recipe_json}")
        return

    # run
    task = args.task
    if task.lower() in ("fusion",):
        task = "Clinic+Radiomics"

    # Build dataset
    clin_raw, rad_raw, time, event = build_xy_from_raw(
        clinical_csv=args.clinical_csv,
        radiomics_csv=args.radiomics_csv,
        clinical_id_col=args.clinical_id_col,
        radiomics_id_col=args.radiomics_id_col,
        time_col=args.time_col,
        event_col=args.event_col,
    )

    clinical_flags = {
        "use_age": int(args.use_age),
        "use_gender": int(args.use_gender),
        "use_histology": int(args.use_histology),
        "use_t_stage": int(args.use_t_stage),
        "use_n_stage": int(args.use_n_stage),
        "use_m_stage": int(args.use_m_stage),
        "use_stage": int(args.use_stage),
    }

    # Recipe
    recipe_entries: List[RecipeEntry] = []
    if args.mode == "exact":
        if not args.recipe_json:
            raise ValueError("EXACT mode requires --recipe_json (from extract).")
        recipe_entries = load_recipe(args.recipe_json)

    models = ["cph", "coxnet", "gbsa"] if args.model == "all" else [args.model]

    results = []
    for m in models:
        if args.mode == "exact":
            ent = pick_recipe_entry(recipe_entries, task=task, model=m)
            train_ids, test_ids = ent.train_ids, ent.test_ids
            selected_features = ent.selected_features
            best_params = ent.best_params
        else:
            # scratch: you must provide split; easiest is still to reuse recipe split
            # If no recipe_json is given, we fall back to a plain 80/20 split with this seed (not recommended for strict reproduction).
            if args.recipe_json:
                recipe_entries = load_recipe(args.recipe_json)
                ent = pick_recipe_entry(recipe_entries, task=task, model="cph")  # any model has the split
                train_ids, test_ids = ent.train_ids, ent.test_ids
            else:
                # fallback random split
                rng = np.random.default_rng(args.seed)
                all_ids = np.array(clin_raw.index.astype(str).tolist())
                rng.shuffle(all_ids)
                n_test = int(round(0.2 * len(all_ids)))
                test_ids = all_ids[:n_test].tolist()
                train_ids = all_ids[n_test:].tolist()
            selected_features = None
            best_params = {}
            # default report-like best params if not provided:
            if m == "cph":
                best_params = {"alpha": 0.8381356590286769, "ties": "efron"}
            elif m == "coxnet":
                best_params = {"l1_ratio": 0.001, "n_alphas": 20}
            elif m == "gbsa":
                best_params = {
                    "criterion": "friedman_mse",
                    "dropout_rate": 0.3,
                    "learning_rate": 0.5710308095913009,
                    "loss": "coxph",
                    "max_depth": 7,
                    "max_features": 0.34046888947419796,
                    "max_leaf_nodes": 12,
                    "min_impurity_decrease": 0.03,
                    "min_samples_leaf": 3,
                    "min_samples_split": 8,
                    "min_weight_fraction_leaf": 0.2,
                    "n_estimators": 100,
                    "subsample": 0.2,
                    "random_state": args.seed,
                }

        # Optional override split
        if args.split_json:
            train_ids, test_ids = load_split_json(args.split_json)

        out = run_one(
            task=task,
            model=m,
            clin_raw=clin_raw,
            rad_raw=rad_raw,
            time=time,
            event=event,
            train_ids=train_ids,
            test_ids=test_ids,
            selected_features=selected_features,
            best_params=best_params,
            seed=args.seed,
            mode=args.mode,
            mrmr_ratio=args.mrmr_ratio,
            mrmr_k=args.mrmr_k,
            bootstrap=args.bootstrap,
            out_dir=args.out_dir,
            clinical_flags=clinical_flags,
            age_impute=args.age_impute,
        )
        results.append(out)

        print("\n" + "-"*72)
        print(f"[{task} | {m} | {args.mode}]")
        print(f"n_train={out['n_train']} n_test={out['n_test']} n_features={out['n_features']}")
        print(f"train_cindex={out['train_cindex']:.4f}  test_cindex={out['test_cindex']:.4f}")
        print(f"boot_mean±std = {out['boot_mean']:.4f} ± {out['boot_std']:.4f}")
        print(f"CI(norm) 95% = [{out['ci_norm_2.5']:.4f}, {out['ci_norm_97.5']:.4f}]")
        print(f"CI(pct)  95% = [{out['ci_pct_2.5']:.4f}, {out['ci_pct_97.5']:.4f}]")
        if m == "coxnet":
            print(f"coxnet best_alpha={out['model_params'].get('best_alpha', None)} best_cv={out['model_params'].get('best_cv_cindex', None)}")

    # save summary
    sum_path = os.path.join(args.out_dir, "summary.json")
    with open(sum_path, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f"\n[OK] Saved summary: {sum_path}")


if __name__ == "__main__":
    main()