_STAGE_MAP = {"I": 0, "II": 1, "IIIa": 2, "IIIb": 3}
_HISTO_MAP = {
    "adenocarcinoma": 0,
    "large cell": 1,
    "nos": 2,
    "squamous cell carcinoma": 3,
}

def _canon_str(x) -> str:
    if pd.isna(x):
        return ""
    return str(x).strip().lower()

def encode_clinical_report_like(df: pd.DataFrame) -> pd.DataFrame:
    """
    Convert raw Lung1 clinical columns into the integer-coded categories
    that match the artifact feature names:
      gender -> 0/1
      Overall.Stage -> 0..3
      Histology -> 0..4 (4=unknown/missing)
      clinical.T.Stage -> 0..5 (0=missing)
      Clinical.N.Stage -> 0..4 (missing -> 5 if needed)
      Clinical.M.Stage -> 0..2   (map 3 -> 2; missing -> 3 if needed)
    and keep age as numeric.
    """
    out = pd.DataFrame(index=df.index)

    # age (numeric)
    out["age"] = pd.to_numeric(df["age"], errors="coerce")

    # gender: female/male -> 0/1
    g = df["gender"].map(lambda x: _canon_str(x))
    # if future unknowns appear, map to 2
    out["gender"] = g.map({"female": 0, "male": 1}).fillna(2).astype(int)

    # Overall.Stage: I/II/IIIa/IIIb -> 0..3 ; missing/other -> 4
    st = df["Overall.Stage"].map(lambda x: str(x).strip() if not pd.isna(x) else "")
    out["Overall.Stage"] = st.map(_STAGE_MAP).fillna(4).astype(int)

    # Histology: map 4 strings -> 0..3 ; missing/other -> 4
    h = df["Histology"].map(lambda x: _canon_str(x))
    out["Histology"] = h.map(_HISTO_MAP).fillna(4).astype(int)

    # T stage: numeric 1..5; missing -> 0
    t = pd.to_numeric(df["clinical.T.Stage"], errors="coerce")
    out["clinical.T.Stage"] = t.fillna(0).astype(int)

    # N stage: numeric 0..4; missing -> 5
    n = pd.to_numeric(df["Clinical.N.Stage"], errors="coerce")
    out["Clinical.N.Stage"] = n.fillna(5).astype(int)

    # M stage: values 0,1,3; map 3 -> 2 ; missing -> 3
    m = pd.to_numeric(df["Clinical.M.Stage"], errors="coerce")
    m = m.map(lambda x: 2 if x == 3 else x)
    out["Clinical.M.Stage"] = m.fillna(3).astype(int)

    return out


def build_clinical_matrix(
    clin_raw: pd.DataFrame,
    train_ids: List[str],
    use_age: int = 1,
    use_gender: int = 1,
    use_histology: int = 1,
    use_t_stage: int = 1,
    use_n_stage: int = 1,
    use_m_stage: int = 1,
    use_stage: int = 1,
    age_impute: str = "mean",
    scale_numeric: bool = True,
) -> Tuple[pd.DataFrame, Dict[str, object]]:
    """
    Build report-like clinical design matrix:
      - integer coding (to match e.g. Histology_4, Overall.Stage_3)
      - one-hot for categorical
      - min-max for age (numeric)

    Returns:
      X_clin (DataFrame with stable column names)
      fitted objects dict
    """
    coded = encode_clinical_report_like(clin_raw)

    # choose columns
    num_cols = []
    cat_cols = []
    if use_age:
        num_cols.append("age")
    if use_gender:
        cat_cols.append("gender")
    if use_histology:
        cat_cols.append("Histology")
    if use_t_stage:
        cat_cols.append("clinical.T.Stage")
    if use_n_stage:
        cat_cols.append("Clinical.N.Stage")
    if use_m_stage:
        cat_cols.append("Clinical.M.Stage")
    if use_stage:
        cat_cols.append("Overall.Stage")

    # Impute numeric
    fitted: Dict[str, object] = {}
    X_num = pd.DataFrame(index=coded.index)
    if num_cols:
        imp = SimpleImputer(strategy=age_impute)
        imp.fit(coded.loc[train_ids, num_cols])
        X_num[num_cols] = imp.transform(coded[num_cols])
        fitted["num_imputer"] = imp

        if scale_numeric:
            scaler = MinMaxScaler()
            scaler.fit(X_num.loc[train_ids, num_cols])
            X_num[num_cols] = scaler.transform(X_num[num_cols])
            fitted["num_scaler"] = scaler

    # One-hot categorical with fixed category sets to ensure feature-name match
    X_cat = pd.DataFrame(index=coded.index)
    if cat_cols:
        categories = []
        for c in cat_cols:
            if c == "gender":
                categories.append([0, 1, 2])
            elif c == "Histology":
                categories.append([0, 1, 2, 3, 4])
            elif c == "Overall.Stage":
                categories.append([0, 1, 2, 3, 4])
            elif c == "clinical.T.Stage":
                categories.append([0, 1, 2, 3, 4, 5])
            elif c == "Clinical.N.Stage":
                categories.append([0, 1, 2, 3, 4, 5])
            elif c == "Clinical.M.Stage":
                categories.append([0, 1, 2, 3])
            else:
                # fallback: infer
                categories.append(sorted(coded[c].dropna().unique().tolist()))

        try:
            ohe = OneHotEncoder(categories=categories, sparse_output=False, handle_unknown="ignore")
        except TypeError:
            ohe = OneHotEncoder(categories=categories, sparse=False, handle_unknown="ignore")
        ohe.fit(coded.loc[train_ids, cat_cols])

        arr = ohe.transform(coded[cat_cols])
        feat_names = list(ohe.get_feature_names_out(cat_cols))
        X_cat = pd.DataFrame(arr, columns=feat_names, index=coded.index)
        fitted["ohe"] = ohe

    X = pd.concat([X_num, X_cat], axis=1)
    return X, fitted


