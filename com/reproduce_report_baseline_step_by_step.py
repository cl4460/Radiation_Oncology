@dataclass
class RecipeEntry:
    task: str               # Radiomics / Clinic / Clinic+Radiomics
    model: str              # cph / coxnet / gbsa
    seed_dir: str           # seed_9 etc (as in artifacts)
    train_ids: List[str]
