def standardize_clinical_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Rename columns to match the training script's expectations."""
    col_map = {}
    for col in df.columns:
        col_clean = col.lower().strip()

        if "patient" in col_clean or "case" in col_clean or col_clean in ["id", "case id", "case_id"]:
            col_map[col] = "patient_id"
        elif ("survival" in col_clean and "time" in col_clean) or col_clean in ["time", "time_days", "os", "os_days"]:
            col_map[col] = "time"
        elif "dead" in col_clean or "event" in col_clean or col_clean in ["status", "survival_status"]:
            col_map[col] = "event"
        elif "overall" in col_clean and "stage" in col_clean:
            col_map[col] = "overall_stage"
        elif (".t." in col_clean or col_clean.startswith("t") or col_clean.startswith("clinical.t")) and "stage" in col_clean:
            col_map[col] = "T"
        elif (".n." in col_clean or col_clean.startswith("n") or col_clean.startswith("clinical.n")) and "stage" in col_clean:
            col_map[col] = "N"
        elif (".m." in col_clean or col_clean.startswith("m") or col_clean.startswith("clinical.m")) and "stage" in col_clean:
            col_map[col] = "M"
        elif "age" in col_clean and "stage" not in col_clean:
            col_map[col] = "age"
        elif "gender" in col_clean or "sex" in col_clean:
            col_map[col] = "gender"

    return df.rename(columns=col_map)


def load_manifest(crop_log_csv: str, clinical_csv: str, require_edt: bool = True) -> pd.DataFrame:
    crop = pd.read_csv(crop_log_csv)
    clin = pd.read_csv(clinical_csv)
    clin = standardize_clinical_columns(clin)

    # Crop log columns vary slightly between runs; handle both.
    # Expect: patient_id, out_ct, out_edt; (out_mask optional), has_segmentation optional
    needed = ["patient_id", "out_ct"]
    if require_edt:
        needed.append("out_edt")
    for c in needed:
        if c not in crop.columns:
            raise ValueError(f"{crop_log_csv} missing required column: {c}")

    cols = ["patient_id", "out_ct"] + (["out_edt"] if "out_edt" in crop.columns else [])
    if "out_mask" in crop.columns:
        cols.append("out_mask")
    if "has_segmentation" in crop.columns:
        cols.append("has_segmentation")

    crop2 = crop[cols].copy()
    crop2 = crop2.rename(columns={"out_ct": "ct_path", "out_edt": "edt_path", "out_mask": "mask_path"})

    # Merge
    m = crop2.merge(clin, on="patient_id", how="inner")

    # Must have survival labels
    if "time" not in m.columns or "event" not in m.columns:
        raise ValueError(
            f"After merging, manifest lacks time/event columns. Got columns: {list(m.columns)[:30]}"
        )

    m = m.dropna(subset=["time", "event"]).copy()
    m["time"] = pd.to_numeric(m["time"], errors="coerce").astype(float)
    m["event"] = pd.to_numeric(m["event"], errors="coerce").astype(float)
    m = m.dropna(subset=["time", "event"]).copy()
    m["time"] = m["time"].astype(int)
    m["event"] = m["event"].astype(int)

    # default has_segmentation if missing
    if "has_segmentation" not in m.columns:
        m["has_segmentation"] = True

    return m


