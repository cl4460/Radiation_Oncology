def fit_clinical_params(train_df: pd.DataFrame) -> ClinicalParams:
    """Fit fold-specific clinical preprocessing on LUNG1-train split."""
    # age
    age_raw = pd.to_numeric(train_df.get("age", pd.Series([np.nan] * len(train_df))), errors="coerce").values.astype(
        np.float32
    )
    age_train_median = float(np.nanmedian(age_raw)) if np.any(~np.isnan(age_raw)) else 0.0

    # StandardScaler fit on age_filled of train split
    age_filled = age_raw.copy()
    age_filled[np.isnan(age_filled)] = age_train_median
    scaler = StandardScaler()
    scaler.fit(age_filled.reshape(-1, 1))

    # T/N/M/overall
    T_num = _parse_T(train_df.get("T", pd.Series([np.nan] * len(train_df))))
    N_num = _parse_N(train_df.get("N", pd.Series([np.nan] * len(train_df))))
    M01, _ = _parse_M(train_df.get("M", pd.Series([np.nan] * len(train_df))))
    ov = _map_overall(train_df.get("overall_stage", pd.Series([np.nan] * len(train_df))))

    return ClinicalParams(
        age_train_median=age_train_median,
        age_scaler_mean=float(scaler.mean_[0]),
        age_scaler_scale=float(scaler.scale_[0] if scaler.scale_[0] > 1e-12 else 1.0),
        T_mode=_safe_mode(T_num, default=2.0),
        N_mode=_safe_mode(N_num, default=1.0),
        M_mode=_safe_mode(M01, default=0.0),
        overall_mode=_safe_mode(ov, default=0.6),
    )


def transform_clinical(df: pd.DataFrame, params: ClinicalParams) -> np.ndarray:
    """Transform ANY dataset (RG or LUNG1) to the 12-dim clinical vector."""
    n = len(df)

    # age
    age_raw = pd.to_numeric(df.get("age", pd.Series([np.nan] * n)), errors="coerce").values.astype(np.float32)
    age_missing = np.isnan(age_raw).astype(np.float32)
    age_filled = age_raw.copy()
    age_filled[np.isnan(age_filled)] = params.age_train_median
    age_scaled = ((age_filled - params.age_scaler_mean) / params.age_scaler_scale).astype(np.float32)

    # gender
    gender_ser = df.get("gender", pd.Series([""] * n)).astype(str).str.upper().str[0]
    gender_male = (gender_ser == "M").astype(np.float32).values

    # T
    T_num = _parse_T(df.get("T", pd.Series([np.nan] * n)))
    T_missing = np.isnan(T_num).astype(np.float32)
    T_filled = T_num.copy()
    T_filled[np.isnan(T_filled)] = params.T_mode
    T_norm = ((T_filled - 1.0) / 3.0).astype(np.float32)

    # N
    N_num = _parse_N(df.get("N", pd.Series([np.nan] * n)))
    N_missing = np.isnan(N_num).astype(np.float32)
    N_filled = N_num.copy()
    N_filled[np.isnan(N_filled)] = params.N_mode
    N_norm = ((N_filled - 0.0) / 3.0).astype(np.float32)

    # M
    M01, M_misc = _parse_M(df.get("M", pd.Series([np.nan] * n)))
    M_missing = np.isnan(M01).astype(np.float32)
    M01_filled = M01.copy()
    M01_filled[np.isnan(M01_filled)] = params.M_mode

    # overall stage
    ov = _map_overall(df.get("overall_stage", pd.Series([np.nan] * n)))
    overall_missing = np.isnan(ov).astype(np.float32)
    ov_filled = ov.copy()
    ov_filled[np.isnan(ov_filled)] = params.overall_mode

    X = np.stack(
        [
            age_scaled,
            age_missing,
            gender_male,
            T_norm,
            T_missing,
            N_norm,
            N_missing,
            M01_filled,
            M_missing,
            M_misc,
            ov_filled,
            overall_missing,
        ],
        axis=1,
    ).astype(np.float32)

    # safety
    X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)
    return X


