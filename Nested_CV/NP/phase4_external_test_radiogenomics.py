"""Phase 4: External Test on NSCLC-Radiogenomics (RG)

What this script does
---------------------
1) Reconstruct the exact LUNG1 CV folds used in phase3_0617.py
2) For each fold checkpoint (fold_0..fold_4/best.pt):
   - Re-fit the *same* clinical feature preprocessing using that fold's LUNG1-train split
     (age StandardScaler, mode-imputation for T/N/M/overall_stage, missing indicators)
   - Run inference on RG Phase2 outputs (CT+EDT already in [0,1])
   - Compute Harrell C-index and Uno IPCW C-index on RG
3) Optionally build an ensemble over the fold models (z-scored risk average)

Assumptions (match your pipeline)
---------------------------------
- RG Phase2 outputs were generated by your window+EDT pipeline (HU window [-1000,400] -> [0,1]).
- Each RG record has out_ct and out_edt (NIfTI) and a patient_id.
- You have LUNG1 crop_log.csv + clinical.csv that were used for training those checkpoints.

Usage example
-------------
python phase4_external_test_radiogenomics.py \
  --lung1_crop_log   /home/lichengze/Research/CNN_pipeline/phase2_outputs/crop_log.csv \
  --lung1_clinical   /home/lichengze/Research/CNN_pipeline/NSCLC-Radiomics-Lung1.clinical.csv \
  --ckpt_root        /home/lichengze/Research/CNN_pipeline/phase3_outputs/learning_rate/learning_rate_corrected/output/lr_7e-4 \
  --rg_crop_log      /home/lichengze/Research/Radiogenomics/phase2_outputs/phase2_crop_log.csv \
  --rg_clinical      /home/lichengze/Research/Radiogenomics/Radiogenomics_clinical_aligned.csv \
  --out_dir          /home/lichengze/Research/Radiogenomics/external_test_lr7e-4

Notes
-----
- Default is to evaluate ONLY cases with has_segmentation==True (recommended for your CT+EDT model).
- If you want to include no-seg cases (center crop + EDT=0), pass --include_no_seg.
"""

