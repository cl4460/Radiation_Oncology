def survival_from_logits(logits: torch.Tensor, n_time_bins: int) -> torch.Tensor:
    haz = torch.sigmoid(logits[:, :n_time_bins])
    surv = torch.cumprod(1.0 - haz, dim=1)
    return surv


@torch.no_grad()
def predict_survival_tta4(
    model: nn.Module,
    img_batch: torch.Tensor,
    clin_batch: torch.Tensor,
    device: torch.device,
    n_time_bins: int,
    use_tta: bool = True,
) -> np.ndarray:
    """4-view TTA (H/W flips) matching phase3_0617.py."""
    model.eval()

    img_batch = img_batch.to(device)
    clin_batch = clin_batch.to(device)

    if not use_tta:
        logits = model(img_batch, clin_batch)
        surv = survival_from_logits(logits, n_time_bins)
        return surv.cpu().numpy()

    views = [
        img_batch,
        torch.flip(img_batch, dims=[-2]),
        torch.flip(img_batch, dims=[-1]),
        torch.flip(img_batch, dims=[-2, -1]),
    ]

    outs = []
    for v in views:
        logits = model(v, clin_batch)
        outs.append(survival_from_logits(logits, n_time_bins))

    return torch.stack(outs, dim=0).mean(dim=0).cpu().numpy()


