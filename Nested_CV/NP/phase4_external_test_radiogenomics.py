def safe_tau_from_train(train_times: np.ndarray, train_events: np.ndarray, test_times: np.ndarray) -> float:
    evt_times = train_times[train_events == 1]
    if evt_times.size == 0:
        # no events in train: fall back to max test time
        return float(np.max(test_times))
    tau = float(np.quantile(evt_times, 0.9))
    # IPCW requires tau <= max(test_times)
    tau = min(tau, float(np.max(test_times) - 1e-3))
    # also guard against non-positive
    tau = max(tau, 1.0)
    return tau


def compute_cindices(
    y_train_struct,
    y_test_struct,
    risk: np.ndarray,
    tau: float,
) -> Dict[str, float]:
    out = {}
    # Harrell
    out["harrell"] = float(
        concordance_index_censored(y_test_struct["event"], y_test_struct["time"], risk)[0]
    )
    # Uno
    out["uno"] = float(concordance_index_ipcw(y_train_struct, y_test_struct, risk, tau=tau)[0])
    return out


